package org.hotel.annotations;

public enum ConfigType {
    /**
     * Тип конфигурационного свойства: авто.
     */
    AUTO,
    /**
     * Тип конфигурационного свойства: строка.
     */
    STRING,
    /**
     * Тип конфигурационного свойства: число.
     */
    INT,
    /**
     * Тип конфигурационного свойства: логическое значение.
     */
    BOOLEAN;
}
